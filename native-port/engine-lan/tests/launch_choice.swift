@main struct LaunchChoiceTests {
    static func main() {
        var choice = EngineLanLaunchChoice()
        precondition(!choice.isLAN && choice.selectedIndex(savedMode:nil) == nil)
        precondition(choice.selectedIndex(savedMode:1) == 0)
        precondition(choice.selectedIndex(savedMode:2) == 1)
        precondition(choice.selectedIndex(savedMode:99) == nil)
        precondition(choice.engineMode(savedMode:1) == 1)
        precondition(choice.engineMode(savedMode:2) == 2)
        precondition(choice.select(index:2) == nil && choice.isLAN)
        precondition(choice.selectedIndex(savedMode:2) == 2)
        precondition(choice.engineMode(savedMode:2) == 1)
        precondition(choice.select(index:99) == nil && choice.isLAN)
        precondition(choice.select(index:0) == 1 && !choice.isLAN)
        precondition(choice.select(index:1) == 2 && !choice.isLAN)
        precondition(choice.engineMode(savedMode:2) == 2)
        let restarted = EngineLanLaunchChoice()
        precondition(!restarted.isLAN && restarted.selectedIndex(savedMode:2) == 1)
        precondition(!restarted.legacyBridgeSelected)
        choice.selectLegacyBridge()
        precondition(choice.legacyBridgeSelected && !choice.isLAN)
        precondition(choice.engineMode(savedMode:1) == 1 && choice.engineMode(savedMode:2) == 2)
        choice.offlineModeChanged()
        precondition(choice.legacyBridgeSelected && !choice.isLAN)
        _ = choice.select(index:2)
        precondition(choice.isLAN && !choice.legacyBridgeSelected)
        choice.selectLegacyBridge()
        _ = choice.select(index:1)
        precondition(!choice.isLAN && !choice.legacyBridgeSelected)
        print("LAUNCH_CHOICES_KEEP_OFFLINE_RAW_VALUES_AND_LAN_IS_EXPLICIT_PASS")
    }
}
