"""Generate browser/native fallback tables from one small authored catalog."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path(__file__).resolve().parents[1] / 'Source/TextLabels.json'


def label_hash(label):
    h = 0
    for c in label.lower():
        h = (h + ord(c)) & 0xffffffff
        h = (h + (h << 10)) & 0xffffffff
        h ^= h >> 6
    h = (h + (h << 3)) & 0xffffffff
    h ^= h >> 11
    return (h + (h << 15)) & 0xffffffff


def outputs(native_only=False):
    rows = json.loads(CATALOG.read_text())
    if not 1 <= len(rows) <= 2048:
        raise ValueError('Bounded label catalog required')
    hashes = set()
    for key, text in rows:
        if not re.fullmatch(r'[A-Z0-9_]+', key) or not text or len(text.encode()) > 512 or '\0' in text:
            raise ValueError('Invalid fallback row: ' + key)
        h = label_hash(key)
        if h in hashes:
            raise ValueError('Duplicate label/hash: ' + key)
        hashes.add(h)
    js = ROOT / 'engine-lan/text_fallback.js'
    original = js.read_text() if not native_only else ''
    start = original.index(' const texts=') if not native_only else 0
    end = original.index('\n function labelHash', start) if not native_only else 0
    browser = original[:start] + ' const texts=' + json.dumps(rows, ensure_ascii=True, separators=(',', ':')) + ';' + original[end:]
    native = '/* Generated by generate_text_labels.py; edit app/Source/TextLabels.json. */\n'
    native += '#define PG_TEXT_LABEL_COUNT ' + str(len(rows)) + '\n'
    native += 'static const struct PGTextLabel { uint32_t hash; const char *text; } pg_text_labels[] = {\n'
    for key, text in sorted(rows, key=lambda row: label_hash(row[0])):
        native += '  {UINT32_C(0x%08x), %s}, /* %s */\n' % (label_hash(key), json.dumps(text, ensure_ascii=True), key)
    native += '};\n'
    result = {CATALOG.with_name('NativeTextLabels.inc'): native}
    if not native_only: result[js] = browser
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    p.add_argument('--native-only', action='store_true')
    args = p.parse_args()
    for path, text in outputs(args.native_only).items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                p.exit(1, 'Generated label table differs: ' + str(path) + '\n')
        else:
            path.write_text(text)
    print('Shared browser/native label tables ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
