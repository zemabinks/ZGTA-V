"""Generate the same vehicle names/categories for UIKit and the browser.

The checked-in JSON contains reference facts, not models, textures or thumbnails.
--import-reference rebuilds it from the official FiveM reference and local base
vehicles.meta; ordinary generation/checking needs neither network nor game data.
"""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

APP = Path(__file__).resolve().parents[1]
CATALOG = APP / 'Resources/vehicle-catalog.json'
CATEGORIES = [
    ('Compacts', 'Compacts', 'car.fill'), ('Sedans', 'Sedans', 'car.fill'),
    ('SUVs', 'SUVs', 'car.side.fill'), ('Coupes', 'Coupes', 'car.side.fill'),
    ('Muscles', 'Muscle cars', 'car.side.fill'), ('Sports Classic', 'Sports classics', 'car.side.fill'),
    ('Sports', 'Sports cars', 'car.side.fill'), ('Super', 'Supercars', 'car.side.fill'),
    ('Motorcycles', 'Motorcycles', 'zgta.motorcycle'), ('Off-Road', 'Off-road', 'zgta.offroad'),
    ('Industrial', 'Industrial', 'zgta.industrial'), ('Utility', 'Utility', 'wrench.fill'),
    ('Vans', 'Vans', 'zgta.van'), ('Cycles', 'Bicycles', 'bicycle'),
    ('Boats', 'Boats & submarines', 'zgta.boat'), ('Helicopters', 'Helicopters', 'zgta.helicopter'),
    ('Planes', 'Planes', 'airplane'), ('Service', 'Service', 'bus.fill'),
    ('Emergency', 'Emergency', 'zgta.beacon'), ('Military', 'Military', 'shield.fill'),
    ('Commercial', 'Commercial', 'zgta.truck'), ('Trains', 'Trains', 'tram.fill'),
    ('Open Wheels', 'Open-wheel racing', 'zgta.racing'), ('Trailers', 'Trailers', 'zgta.trailer')
]


def import_reference(reference, metadata):
    text = reference.read_text()
    records = {}
    for block in re.split(r'^## ', text, flags=re.M)[1:]:
        category = block.splitlines()[0].strip()
        if category not in {c[0] for c in CATEGORIES}:
            raise ValueError('Unreviewed reference category: ' + category)
        for label, model in re.findall(r'<strong>Display Name:</strong>\s*(.*?)</span>.*?<strong>Model Name:</strong>\s*(.*?)</span>', block, re.S):
            model = model.strip().lower()
            if model in records:
                raise ValueError('Duplicate reference model: ' + model)
            records[model] = dict(model=model, name=html.unescape(re.sub('<[^>]*>', '', label)).strip(),
                                  category=category, base=False, kind='train' if category == 'Trains' else 'vehicle')
    base = ET.fromstring(metadata.read_bytes()).findall('./InitDatas/Item')
    for item in base:
        model = item.findtext('modelName', '').strip().lower()
        if model not in records:
            raise ValueError('Base model absent from reference: ' + model)
        records[model]['base'] = True
        kind = item.findtext('type', '').strip()
        if kind == 'VEHICLE_TYPE_TRAILER':
            records[model].update(category='Trailers', kind='trailer')
        elif kind == 'VEHICLE_TYPE_TRAIN':
            records[model].update(category='Trains', kind='train')
    doc = dict(format=1, reference='https://docs.fivem.net/docs/game-references/vehicle-references/vehicle-models/',
               reference_sha256=hashlib.sha256(reference.read_bytes()).hexdigest(),
               base_metadata_sha256=hashlib.sha256(metadata.read_bytes()).hexdigest(),
               thumbnail_base_url='https://docs-backend.fivem.net/vehicles/',
               base_model_count=len(base), categories=[dict(id=c, name=n, icon=i) for c, n, i in CATEGORIES],
               vehicles=sorted(records.values(), key=lambda r: r['model']))
    CATALOG.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + '\n')


def outputs():
    data = json.loads(CATALOG.read_text())
    sys.path.insert(0,str(APP.parent/'engine-lan'))
    import mod_previews
    data['mod_previews']=mod_previews.load()
    if data.get('thumbnail_base_url') != 'https://docs-backend.fivem.net/vehicles/':
        raise ValueError('Unexpected vehicle thumbnail origin')
    categories = {c['id'] for c in data['categories']}
    names = set()
    for row in data['vehicles']:
        model = row['model']
        if not re.fullmatch('[a-z][a-z0-9_]{0,62}', model) or model in names or row['category'] not in categories:
            raise ValueError('Invalid catalog model/category: ' + model)
        if row['kind'] not in ('vehicle', 'trailer', 'train') or not isinstance(row['base'], bool):
            raise ValueError('Invalid catalog metadata: ' + model)
        names.add(model)
    encoded = json.dumps(data, ensure_ascii=True, separators=(',', ':'))
    js = '/* Generated by app/Scripts/generate_vehicle_catalog.py. */\n(function(root){\n const data=' + encoded + ';\n'
    js += " const models=new Set(data.vehicles.map(v=>v.model)),mod=v=>v&&v.kind==='mod'&&Object.hasOwn(data.mod_previews,v.model)?data.mod_previews[v.model]:null;\n const api={thumbnailBaseURL:data.thumbnail_base_url,thumbnailURL:v=>mod(v)?'/zema-lab/'+mod(v).file:v&&v.kind!=='mod'&&models.has(v.model)?data.thumbnail_base_url+v.model+'.webp':null,thumbnailCredit:v=>mod(v)?mod(v).credit:v?.kind==='mod'?'Installed mod vehicle':'Reference: FiveM / Cfx.re',categories:Object.freeze(data.categories.map(Object.freeze)),vehicles:Object.freeze(data.vehicles.map(Object.freeze))};\n root.ZemaVehicleCatalog=Object.freeze(api);if(typeof module==='object')module.exports=api;\n})(globalThis);\n"
    swift = '// Generated by Scripts/generate_vehicle_catalog.py; edit Resources/vehicle-catalog.json.\n'
    swift += 'extension VehicleCatalog {\n    static let thumbnailBaseURL = ' + json.dumps(data['thumbnail_base_url']) + '\n    static let categories: [Category] = [\n'
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    for c in data['categories']:
        swift += '        Category(id: %s, name: %s, icon: %s),\n' % tuple(quote(c[k]) for k in ('id', 'name', 'icon'))
    swift += '    ]\n    static let vehicles: [Entry] = [\n'
    for r in data['vehicles']:
        swift += '        Entry(model: %s, name: %s, category: %s, base: %s, kind: %s),\n' % (
            quote(r['model']), quote(r['name']), quote(r['category']), str(r['base']).lower(), quote(r['kind']))
    swift += '    ]\n}\n'
    swift += 'extension VehicleCatalog {\n    static let modPreviews: [String: (file: String, credit: String)] = [\n'
    for model,row in data['mod_previews'].items():
        swift += '        %s: (file: %s, credit: %s),\n' % (quote(model),quote(row['file']),quote(row['credit']))
    swift += '    ]\n}\n'
    return {APP / 'App/VehicleCatalogData.swift': swift, APP.parent / 'engine-lan/vehicle-catalog.js': js}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    p.add_argument('--import-reference', type=Path)
    p.add_argument('--base-metadata', type=Path)
    a = p.parse_args()
    if a.import_reference:
        if a.check or not a.base_metadata:
            p.error('Import requires --base-metadata and cannot use --check')
        import_reference(a.import_reference, a.base_metadata)
    for path, text in outputs().items():
        if a.check:
            if path.read_text() != text:
                p.exit(1, 'Generated vehicle catalog differs: ' + str(path) + '\n')
        else:
            path.write_text(text)
    print('Shared vehicle catalog ' + ('verified' if a.check else 'generated'))


if __name__ == '__main__':
    main()
