"""One small compatibility catalog for native/browser asset-name fallbacks."""
import argparse,json,re
from pathlib import Path
APP=Path(__file__).resolve().parents[1]
CATALOG=APP/'Source/BlipFallbacks.json'

def outputs():
 rows=json.loads(CATALOG.read_text());seen=set()
 if not 1<=len(rows)<=64:raise ValueError('Bounded icon catalog required')
 for requested,target,name,description in rows:
  if type(requested) is not int or type(target) is not int or not 426<=requested<=1024 or not 1<=target<426 or requested in seen:raise ValueError('Invalid sprite mapping')
  if not re.fullmatch(r'radar_[a-z0-9_]{1,48}',name) or not isinstance(description,str) or not 1<=len(description)<=160:raise ValueError('Invalid asset description')
  seen.add(requested)
 rows=sorted(rows);inc='/* Generated by generate_blip_fallbacks.py. */\n'
 inc+='static const struct PGBlipFallback { int32_t requested,target;const char *asset; } pg_blip_fallbacks[] = {\n'
 for a,b,n,_ in rows:inc+='  {%d,%d,%s},\n'%(a,b,json.dumps(n))
 inc+='};\n'
 js=APP.parent/'engine-lan/blip_sprites.js';original=js.read_text();start=original.index(' const FALLBACKS=');end=original.index('\n function ',start)
 return {APP/'Source/NativeBlipFallbacks.inc':inc,js:original[:start]+' const FALLBACKS='+json.dumps([r[:3] for r in rows],separators=(',',':'))+';'+original[end:]}

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
 for path,text in outputs().items():
  if a.check:
   if not path.exists() or path.read_text()!=text:p.exit(1,'Generated icon map differs: '+str(path)+'\n')
  else:path.write_text(text)
 print('Shared sprite fallbacks '+('verified' if a.check else 'generated'))
if __name__=='__main__':main()
